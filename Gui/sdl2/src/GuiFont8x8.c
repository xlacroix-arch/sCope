TlsGuiSimpleFont *TlsGuiNewAsciiFont8x8(void) {
    TlsGuiSimpleFont *r;
    TlsGuiTextureFormat *bmf;
    static TlsI2dRange Glyphs[128];
    static int Inited = (0!=0);
    if (!Inited) {
        TlsI2dRange *p;
        int i;
        p = Glyphs;
        for (i=0;i<128;i++) {
            p->b.x[0] = (i&0x7)<<3;
            p->b.x[1] = (i&0x78);
            p->e.x[0] = p->b.x[0]+8;
            p->e.x[1] = p->b.x[1]+8;
            p++;
        }
        Inited = (0==0);
    }
    rPush(r);
    bmf = TlsGuiTxtrFormatBitmap();
    r->Sheet = TlsGuiTextureNew(bmf,&TlsGuiPaletteGreyScale,64,128);
    r->GlyphNb = 128;
    r->Glyphs = Glyphs;
    r->dx=8; r->dy=8;
    Font8x8Fill(r->Sheet->data,1,r->Sheet->pitch);
    return r;
}

